// Counting Numbers (1 to 100 with Devnagari, English word & Hindi word)
export const COUNTING_DATA = Array.from({ length: 100 }, (_, i) => {
  const num = i + 1;
  const hindiDigits = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"];
  const devanagari = num
    .toString()
    .split("")
    .map((d) => hindiDigits[parseInt(d)])
    .join("");

  const hindiNames: Record<number, string> = {
    1: "एक", 2: "दो", 3: "तीन", 4: "चार", 5: "पाँच",
    6: "छह", 7: "सात", 8: "आठ", 9: "नौ", 10: "दस",
    11: "ग्यारह", 12: "बारह", 13: "तेरह", 14: "चौदह", 15: "पंद्रह",
    16: "सोलह", 17: "सत्रह", 18: "अट्ठारह", 19: "उन्नीस", 20: "बीस",
    25: "पच्चीस", 30: "तीस", 40: "चालीस", 50: "पचास",
    60: "साठ", 70: "सत्तर", 80: "अस्सी", 90: "नब्बे", 100: "सौ"
  };

  return {
    number: num,
    devanagari,
    wordEn: `Number ${num}`,
    wordHi: hindiNames[num] || `${num}`,
  };
});

