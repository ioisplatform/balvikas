// MASTER RESOLVER: Get real high-definition photo for ANY page number from 1 to 720
export function getRealPhotoForPage(
  pageNum: number,
  pageType: string,
  heroChar?: string,
  heroWord?: string
): RealPhotoItem {
  // Page 1: Cover
  if (pageNum === 1 || pageType === "cover") {
    return {
      url: "/src/assets/images/bal_vikas_cover_1789232263344.jpg",
      alt: "IOIS बाल विकास - सम्पूर्ण डिजिटल अध्ययन पुस्तिका",
      labelHi: "IOIS बाल विकास आधिकारिक आमुख पृष्ठ",
      labelEn: "Official Book Cover",
    };
  }

  // Page 2-5: Table of Contents
  if (pageNum >= 2 && pageNum <= 5) {
    return {
      url: "https://images.unsplash.com/photo-1512820790803-83ca734da794?w=800&auto=format&fit=crop&q=80",
      alt: "720 पृष्ठों की क्रमबद्ध पाठ्यक्रम अनुक्रमणिका",
      labelHi: "संपूर्ण 720 पृष्ठों की अध्ययन अनुक्रमणिका",
      labelEn: "Complete 720-Page Study Curriculum",
    };
  }

  // English Alphabet Intro (A to Z)
  if (pageType === "alphabet_intro" && heroChar) {
    const key = heroChar.toUpperCase();
    if (key === "A") {
      return {
        url: "/src/assets/images/a_for_apple_art_1789232283132.jpg",
        alt: "A for Apple - High Definition Real Apple",
        labelHi: "A for Apple (सेब)",
        labelEn: "Fresh Red Apple",
      };
    }
    if (ALPHABET_REAL_PHOTOS[key]) {
      return ALPHABET_REAL_PHOTOS[key];
    }
  }

  // Tracing Sheets (Alphabet Trace, Swar Trace, Vyanjan Trace)
  if (pageType === "alphabet_trace" || pageType === "swar_trace" || pageType === "vyanjan_trace") {
    return TRACING_BANNER_PHOTO;
  }

  // Hindi Swar (अ to अः)
  if (pageType === "swar_intro" && heroChar) {
    if (HINDI_SWAR_REAL_PHOTOS[heroChar]) {
      return HINDI_SWAR_REAL_PHOTOS[heroChar];
    }
  }

  // Hindi Vyanjan (क to ज्ञ)
  if (pageType === "vyanjan_intro" && heroChar) {
    if (HINDI_VYANJAN_REAL_PHOTOS[heroChar]) {
      return HINDI_VYANJAN_REAL_PHOTOS[heroChar];
    }
  }

  // Barakhadi (Pages 156 to 185)
  if (pageType === "barakhadi") {
    return BARAKHADI_REAL_PHOTOS[pageNum % BARAKHADI_REAL_PHOTOS.length];
  }

  // Word Formation (Pages 186 to 225)
  if (pageType === "words") {
    for (const [key, photo] of Object.entries(WORD_REAL_PHOTOS)) {
      if (heroWord?.includes(key) || (heroChar && key.includes(heroChar))) {
        return photo;
      }
    }
    const wordKeys = Object.keys(WORD_REAL_PHOTOS);
    const chosenKey = wordKeys[pageNum % wordKeys.length];
    return WORD_REAL_PHOTOS[chosenKey];
  }

  // Poems (Pages 226 to 260)
  if (pageType === "poem") {
    for (const [key, photo] of Object.entries(POEM_REAL_PHOTOS)) {
      if (heroWord?.includes(key) || (heroChar && key.includes(heroChar))) {
        return photo;
      }
    }
    const poemKeys = Object.keys(POEM_REAL_PHOTOS);
    const chosenKey = poemKeys[pageNum % poemKeys.length];
    return POEM_REAL_PHOTOS[chosenKey];
  }

  // Moral Stories (Pages 261 to 295)
  if (pageType === "story") {
    for (const [key, photo] of Object.entries(STORY_REAL_PHOTOS)) {
      if (heroWord?.includes(key) || (heroChar && key.includes(heroChar))) {
        return photo;
      }
    }
    const storyKeys = Object.keys(STORY_REAL_PHOTOS);
    const chosenKey = storyKeys[pageNum % storyKeys.length];
    return STORY_REAL_PHOTOS[chosenKey];
  }

  // Math Counting 1 to 50 & 51 to 100 (Pages 296 to 395)
  if (pageType === "counting_item" || pageType === "counting_advanced") {
    const itemIndex = pageNum % MATH_COUNT_REAL_PHOTOS.length;
    return MATH_COUNT_REAL_PHOTOS[itemIndex];
  }

  // Math Tables (Pages 396 to 435)
  if (pageType === "table") {
    return MATH_TABLES_REAL_PHOTO;
  }

  // Math Operations (+, -, ×, ÷) (Pages 436 to 560)
  if (
    pageType === "addition" ||
    pageType === "subtraction" ||
    pageType === "multiplication" ||
    pageType === "division"
  ) {
    const itemIndex = (pageNum * 3) % MATH_COUNT_REAL_PHOTOS.length;
    return MATH_COUNT_REAL_PHOTOS[itemIndex];
  }

  // Colors (Pages 561 to 575)
  if (pageType === "colors") {
    for (const [key, photo] of Object.entries(COLORS_REAL_PHOTOS)) {
      if (heroWord?.includes(key) || (heroChar && key.includes(heroChar))) {
        return photo;
      }
    }
    const colKeys = Object.keys(COLORS_REAL_PHOTOS);
    return COLORS_REAL_PHOTOS[colKeys[pageNum % colKeys.length]];
  }

  // Shapes (Pages 576 to 590)
  if (pageType === "shapes") {
    for (const [key, photo] of Object.entries(SHAPES_REAL_PHOTOS)) {
      if (heroWord?.includes(key) || (heroChar && key.includes(heroChar))) {
        return photo;
      }
    }
    const shKeys = Object.keys(SHAPES_REAL_PHOTOS);
    return SHAPES_REAL_PHOTOS[shKeys[pageNum % shKeys.length]];
  }

  // GK & Body Parts (Pages 591 to 650)
  if (pageType === "gk") {
    for (const [key, photo] of Object.entries(GK_REAL_PHOTOS)) {
      if (heroWord?.includes(key) || (heroChar && key.includes(heroChar))) {
        return photo;
      }
    }
    const gkKeys = Object.keys(GK_REAL_PHOTOS);
    return GK_REAL_PHOTOS[gkKeys[pageNum % gkKeys.length]];
  }

  // Daily Homework & Worksheets (Pages 651 to 719)
  if (pageType === "homework") {
    return HOMEWORK_REAL_PHOTOS[pageNum % HOMEWORK_REAL_PHOTOS.length];
  }

  // Certificate (Page 720)
  if (pageNum === 720 || pageType === "certificate") {
    return CERTIFICATE_REAL_PHOTO;
  }

  // Default Fallback Photo
  return {
    url: "https://images.unsplash.com/photo-1503676260728-1c00da094a0b?w=800&auto=format&fit=crop&q=80",
    alt: "IOIS बाल विकास डिजिटल अध्ययन",
    labelHi: "IOIS बाल विकास सचित्र अध्ययन सामग्री",
    labelEn: "Child Development Study Material",
  };
}
